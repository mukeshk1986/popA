-- Step 1: Create comprehensive view with all transformations
CREATE OR REPLACE TEMPORARY VIEW current_batch_member_enrollee AS
SELECT
	TRIM(stage.HOME_PLAN_ID_CD) AS HOME_PLAN_ID_CD, COALESCE(risk.BID, 0) AS MEMBER_BID,
	TRIM(stage.MEMB_ID_CD) AS MEMB_ID_CD, TRIM(stage.BHI_MEMB_ID) AS BHI_MEMB_ID,
	CASE
		WHEN TRIM(stage.CONTRACT_BEGIN_DT) RLIKE '^[0-9]{8}$'
			THEN to_date(TRIM(stage.CONTRACT_BEGIN_DT), 'yyyyMMdd')
		WHEN TRIM(stage.CONTRACT_BEGIN_DT) RLIKE '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'
			THEN to_date(TRIM(stage.CONTRACT_BEGIN_DT), 'yyyy-MM-dd')
		WHEN TRIM(stage.CONTRACT_BEGIN_DT) RLIKE '^[0-9]{1,2}/[0-9]{1,2}/[0-9]{4}$'
			THEN to_date(TRIM(stage.CONTRACT_BEGIN_DT), 'M/d/yyyy')
		ELSE NULL
	END AS CONTRACT_BEGIN_DT,
	CASE
		WHEN TRIM(stage.CONTRACT_END_DT) RLIKE '^[0-9]{8}$'
			THEN to_date(TRIM(stage.CONTRACT_END_DT), 'yyyyMMdd')
		WHEN TRIM(stage.CONTRACT_END_DT) RLIKE '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'
			THEN to_date(TRIM(stage.CONTRACT_END_DT), 'yyyy-MM-dd')
		WHEN TRIM(stage.CONTRACT_END_DT) RLIKE '^[0-9]{1,2}/[0-9]{1,2}/[0-9]{4}$'
			THEN to_date(TRIM(stage.CONTRACT_END_DT), 'M/d/yyyy')
		ELSE NULL
	END AS CONTRACT_END_DT,
	TRIM(stage.POP_ID) AS POP_ID, TRIM(stage.ACCT_CD) AS ACCT_CD, TRIM(stage.GRP_CD) AS GRP_CD,
	TRIM(stage.SUBGRP_CD) AS SUBGRP_CD, TRIM(stage.PROD_ID_CD) AS PROD_ID_CD,
	TRIM(stage.SOURCE_LOAD_MONTH) AS SOURCE_LOAD_MONTH,
	ROW_NUMBER() OVER (
		PARTITION BY
			TRIM(stage.HOME_PLAN_ID_CD),
			TRIM(stage.MEMB_ID_CD),
			TRIM(stage.BHI_MEMB_ID),
			CASE
				WHEN TRIM(stage.CONTRACT_BEGIN_DT) RLIKE '^[0-9]{8}$'
					THEN to_date(TRIM(stage.CONTRACT_BEGIN_DT), 'yyyyMMdd')
				WHEN TRIM(stage.CONTRACT_BEGIN_DT) RLIKE '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'
					THEN to_date(TRIM(stage.CONTRACT_BEGIN_DT), 'yyyy-MM-dd')
				WHEN TRIM(stage.CONTRACT_BEGIN_DT) RLIKE '^[0-9]{1,2}/[0-9]{1,2}/[0-9]{4}$'
					THEN to_date(TRIM(stage.CONTRACT_BEGIN_DT), 'M/d/yyyy')
				ELSE NULL
			END,
			CASE
				WHEN TRIM(stage.CONTRACT_END_DT) RLIKE '^[0-9]{8}$'
					THEN to_date(TRIM(stage.CONTRACT_END_DT), 'yyyyMMdd')
				WHEN TRIM(stage.CONTRACT_END_DT) RLIKE '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'
					THEN to_date(TRIM(stage.CONTRACT_END_DT), 'yyyy-MM-dd')
				WHEN TRIM(stage.CONTRACT_END_DT) RLIKE '^[0-9]{1,2}/[0-9]{1,2}/[0-9]{4}$'
					THEN to_date(TRIM(stage.CONTRACT_END_DT), 'M/d/yyyy')
				ELSE NULL
			END,
			TRIM(stage.POP_ID), TRIM(stage.ACCT_CD), TRIM(stage.GRP_CD), TRIM(stage.SUBGRP_CD),
			TRIM(stage.PROD_ID_CD), TRIM(stage.SOURCE_LOAD_MONTH)
		ORDER BY COALESCE(stage.UPDATED_DATE, stage.CREATED_DATE, CURRENT_TIMESTAMP()) DESC
	) rn
FROM (
	SELECT * FROM ${catalog}.${schema_ingestion}.STAGE_MEMBER_ENROLLEE_HISTORY
	WHERE SOURCE_LOAD_MONTH = ${SOURCE_LOAD_MONTH}
) stage
LEFT OUTER JOIN ${catalog}.${gap_schema_transformation}.MEMBER_ID risk
	ON risk.HOME_PLAN_ID_CD = stage.HOME_PLAN_ID_CD
	AND risk.MEMBER_ID_CD = stage.MEMB_ID_CD;

-- Step 2: MERGE INTO MEMBER_ENROLLEE_HISTORY
MERGE INTO ${catalog}.${gap_schema_transformation}.MEMBER_ENROLLEE_HISTORY AS TARGET
USING (

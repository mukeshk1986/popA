sequence_dates AS (
	SELECT *,
		-- Only the open-ended / corrupt sentinel end date (9999-12-31) is
		-- collapsed to the current year so it does not explode a single
		-- enrollment into thousands of year-ly rows. Genuine future end dates
		-- (e.g. 2028-12-31) are kept as-is and split through their real end
		-- year. greatest(...) keeps the range ascending when a sentinel row
		-- has a begin year later than the current year. The true end date is
		-- preserved downstream: the final COVRG_END_DT is derived via
		-- least(COVRG_END_DT_ORIG, make_date(yr,12,31)), and COVRG_END_DT_ORIG
		-- is retained in SEG2_ID.
		sequence(
			year(COVRG_BEGIN_DT_ORIG),
			greatest(
				year(COVRG_BEGIN_DT_ORIG),
				CASE
					WHEN year(COVRG_END_DT_ORIG) >= 9999 THEN year(current_date())
					ELSE year(COVRG_END_DT_ORIG)
				END
			)
		) AS year_seq
	FROM base_data
	WHERE COVRG_BEGIN_DT_ORIG IS NOT NULL
		AND COVRG_END_DT_ORIG IS NOT NULL
		AND COVRG_BEGIN_DT_ORIG <= COVRG_END_DT_ORIG
),

sequence_dates_explode AS (
	SELECT *,
		'explode(year_seq) AS yr
	FROM sequence_dates
),

-- Two stage records with different COVRG_BEGIN_DT_ORIG can produce the same
-- computed COVRG_BEGIN_DT after year-splitting (e.g. a multi-year span clipped
-- to Jan 1 collides with a record that genuinely starts on Jan 1 of that year),
-- causing DELTA_MULTIPLE_SOURCE_ROW_MATCHING_TARGET_ROW_IN_MERGE.
-- COVRG_BEGIN_DT and COVRG_END_DT are computed here so the dedup join key
-- matches the final MERGE key exactly. QUALIFY filters without a subquery.
-- Prefer the record with the latest original begin date (most specific to the
-- year segment), then break ties by LOAD_DATE DESC.
sequence_dates_deduped AS (
	SELECT *,
		greatest(COVRG_BEGIN_DT_ORIG, make_date(yr, 1, 1)) AS COVRG_BEGIN_DT,
		least(COVRG_END_DT_ORIG, make_date(yr, 12, 31)) AS COVRG_END_DT,
		ROW_NUMBER() OVER (
			PARTITION BY
				HOME_PLAN_ID_CD,
				MEMB_ID_CD,
				greatest(COVRG_BEGIN_DT_ORIG, make_date(yr, 1, 1)),
				-- Keep concurrent product/subscriber segments distinct so they are not
				-- collapsed to one row per year. Must match the MERGE join key exactly.
				PROD_ID_CD,
				PROD_TYPE_CD,
				SUB_ID
			ORDER BY
				COVRG_BEGIN_DT_ORIG DESC,
				LOAD_DATE DESC
		) AS dedup_rn
	FROM sequence_dates_explode
	QUALIFY dedup_rn = 1
),
